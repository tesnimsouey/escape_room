import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const base=process.env.TEST_BASE_URL || 'http://localhost:3001';
if(!['localhost','127.0.0.1'].includes(new URL(base).hostname) || process.env.DISPOSABLE_TEST_DB !== 'yes') throw new Error('Requires an explicitly disposable local database');
const line=readFileSync('.dev.vars','utf8').split('\n').find(s=>/^ADMIN_PASSWORD\s*=/.test(s));
const password=line.slice(line.indexOf('=')+1).trim().replace(/^(["'])(.*)\1$/,'$2');
let checks=0;
async function request(path,body,cookie,status=200) {
 const r=await fetch(base+path,{method:body===undefined?'GET':'POST',headers:{'Content-Type':'application/json',...(cookie?{Cookie:cookie}:{})},body:body===undefined?undefined:JSON.stringify(body)});
 const data=await r.json();assert.equal(r.status,status,JSON.stringify(data));checks++;return {data,cookie:r.headers.get('set-cookie')?.split(';')[0]};
}
const {cookie:admin}=await request('/api/admin/login',{password});
const action=body=>request('/api/admin/action',body,admin);
const overview=async()=>(await request('/api/admin/overview',undefined,admin)).data;
await action({action:'resetAll',removeTeams:true});
await request('/api/admin/action',{action:'resetAll',renewAccess:true},undefined,401);
await action({action:'createTeams',count:2});
let teams=(await overview()).teams;
const first=teams[0];
const {cookie:player}=await request('/api/join',{code:first.code,name:first.name});
await action({action:'start'});
await request('/api/hint',{puzzle:1},player);
await request('/api/submit',{puzzle:1,answers:{check:'18:20',sighting:'18:12'},explanation:'عزة شافت المفتاح على 18:12 والتثبّت على 18:20 ما تثبتش وجوده.'},player);
await action({action:'lock'});await action({action:'reveal'});
assert.equal((await overview()).teams.find(t=>t.id===first.id).solved,1);
await action({action:'resetAll'});
let data=await overview();
assert.equal(data.event.phase,'lobby');assert.equal(data.event.locked,false);assert.equal(data.event.revealed,false);
assert.equal(data.review.length,0);
assert.ok(data.teams.every(t=>t.solved===0&&t.total===0&&t.hints===0&&t.wrong===0&&!t.finished_at));
assert.deepEqual(data.teams.map(t=>t.code).sort(),teams.map(t=>t.code).sort());
assert.equal((await request('/api/state',undefined,player)).data.stage,'lobby');
await request('/api/join',{code:first.code,name:first.name});
await action({action:'resetAll',renewAccess:true});
data=await overview();
assert.deepEqual(data.teams.map(t=>[t.id,t.name,t.variant]).sort(),teams.map(t=>[t.id,t.name,t.variant]).sort());
assert.ok(data.teams.every(t=>!teams.some(old=>old.code===t.code)));
await request('/api/state',undefined,player,401);
await request('/api/join',{code:first.code,name:first.name},undefined,404);
const renewed=data.teams.find(t=>t.id===first.id);
const link=new URL(`/?code=${encodeURIComponent(renewed.code)}`,base);
const {cookie:fresh}=await request('/api/join',{code:link.searchParams.get('code'),name:renewed.name});
assert.equal((await request('/api/state',undefined,fresh)).data.stage,'lobby');
await action({action:'start'});
await request('/api/submit',{puzzle:1,answers:{check:'18:20',sighting:'18:12'},explanation:'عزة شافت المفتاح على 18:12 والتثبّت على 18:20 ما تثبتش وجوده.'},fresh);
assert.equal((await request('/api/state',undefined,fresh)).data.solved,1);
await action({action:'resetAll',removeTeams:true});
const empty=await overview();
assert.equal(empty.teams.length,0);
assert.equal(empty.review.length,0);
assert.equal(empty.event.phase,'lobby');
await request('/api/state',undefined,fresh,401);
await request('/api/join',{code:renewed.code,name:renewed.name},undefined,404);
await action({action:'createTeams',count:3});
const recreated=(await overview()).teams;
assert.equal(recreated.length,3);
assert.ok(recreated.every(t=>!data.teams.some(old=>old.id===t.id || old.code===t.code)));
const newTeam=recreated[0];
const {cookie:newCookie}=await request('/api/join',{code:newTeam.code,name:newTeam.name});
assert.equal((await request('/api/state',undefined,newCookie)).data.stage,'lobby');
console.log(`${checks} HTTP checks passed: reset, preserved links, rotated codes, revoked sessions, fresh joins, replay, complete deletion and new-team creation.`);
